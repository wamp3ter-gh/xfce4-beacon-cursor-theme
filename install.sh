# install.sh: install the Beacon cursor themes into ~/.icons, and switch Xfce to one.
#
# ~/.icons is the only per-user directory libXcursor searches.
#
# Usage:
#   ./install.sh
#   ./install.sh --uninstall
#
# Arguments:
#   - none: install, and switch Xfce when xfconf-query exists
#   - --uninstall: remove every Beacon cursor theme from ~/.icons
#
# Where the themes come from:
#   - build/ next to this script: install from it (a repository after ./build.sh,
#     or an unpacked release)
#   - a repository without build/: stop; run ./build.sh first
#   - this script on its own: download the latest release and install from it
#   - it never builds
#
# Environment:
#   - BEACON_THEME: theme to switch to (default beacon-yellow)
#   - BEACON_SIZE: cursor size in px (default 48)
#   - BEACON_URL: the release archive to download
#     (default: the latest release on GitLab)
#
# Safety:
#   - a folder in ~/.icons that build.sh did not make is never removed or overwritten
#   - every check runs before anything changes
#   - each theme is copied beside the old one, then swapped in
#   - so a failed copy leaves the old theme in place
#   - a download goes to a temporary folder, removed however the run ends
#
# Needs:
#   - curl and tar, only when downloading
set -eu

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
NAME=xfce4-beacon-cursor-theme
URL=${BEACON_URL:-https://gitlab.com/wamp3ter/$NAME/-/releases/permalink/latest/downloads/$NAME.tar.gz}
THEME=${BEACON_THEME:-beacon-yellow}
SIZE=${BEACON_SIZE:-48}
MARK='generated by xfce4-beacon-cursor-theme build.sh'
DEST=$HOME/.icons

die() {
	echo "install.sh: $*" >&2
	exit 1
}
# ours <dir>: the theme in <dir> came from this repo's build.sh
ours() { grep -qsF "$MARK" "$1/index.theme"; }

case ${1:-} in
'') ;;
--uninstall)
	[ $# -eq 1 ] || die "--uninstall takes no other arguments"
	removed=0
	for d in "$DEST"/*/; do
		d=${d%/}
		if ours "$d"; then
			rm -r "$d"
			echo "removed $d"
			removed=$((removed + 1))
		fi
	done
	echo "$removed Beacon cursor theme(s) removed; pick another cursor theme if one was in use"
	exit 0
	;;
*) die "unknown argument '$1' (usage: ./install.sh | ./install.sh --uninstall)" ;;
esac

# --- source: the build/ folder to install from ---------------------------------
TMP=""
cleanup() { if [ -n "$TMP" ]; then rm -rf "$TMP"; fi; }
trap cleanup EXIT
if [ -d "$ROOT/build" ]; then
	SRC=$ROOT/build
elif [ -f "$ROOT/build.sh" ]; then
	die "no build/; run ./build.sh first"
else
	missing=""
	for c in curl tar; do command -v "$c" >/dev/null || missing="$missing $c"; done
	[ -z "$missing" ] || die "missing tools:$missing (needed to download the release)"
	TMP=$(mktemp -d)
	echo "downloading $URL"
	curl -fsSL -o "$TMP/release.tar.gz" "$URL" || die "could not download $URL"
	tar -xzf "$TMP/release.tar.gz" -C "$TMP" || die "could not unpack $URL"
	SRC=$TMP/$NAME/build
	[ -d "$SRC" ] || die "the archive from $URL has no $NAME/build/"
fi

# --- checks: nothing changes until all of these pass ---------------------------
built=""
for d in "$SRC"/*/; do
	d=${d%/}
	if ours "$d"; then built="$built $(basename "$d")"; fi
done
[ -n "$built" ] || die "$SRC holds no themes"
case " $built " in
*" $THEME "*) ;;
*) die "no theme '$THEME' to install (available:$built)" ;;
esac
case $SIZE in
'' | *[!0-9]*) die "BEACON_SIZE must be a whole number of pixels, not '$SIZE'" ;;
esac

clashes=""
for n in $built; do
	dest=$DEST/$n
	if [ -e "$dest" ] || [ -L "$dest" ]; then
		ours "$dest" || clashes="$clashes $dest"
	fi
done
[ -z "$clashes" ] || die "these exist and are not Beacon cursor themes, so nothing was changed:$clashes"

# --- changes ------------------------------------------------------------------
mkdir -p "$DEST"
for n in $built; do
	dest=$DEST/$n
	tmp=$DEST/.$n.beacon-new
	rm -rf "$tmp"
	cp -a "$SRC/$n" "$tmp"
	if [ -e "$dest" ] || [ -L "$dest" ]; then rm -r "$dest"; fi
	mv "$tmp" "$dest"
	echo "installed $dest"
done

# Xfce (xsettings): GTK apps pick this up live.
if command -v xfconf-query >/dev/null; then
	xfconf-query -c xsettings -p /Gtk/CursorThemeName -s "$THEME"
	xfconf-query -c xsettings -p /Gtk/CursorThemeSize -s "$SIZE"
	echo "switched Xfce to $THEME (size $SIZE)"
else
	echo "installed; xfconf-query not found, so select $THEME in your desktop's cursor settings"
fi
